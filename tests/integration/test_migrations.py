"""Migration lifecycle.

A migration that cannot be reversed and re-applied is not a migration, it is a
one-way schema edit. These tests run against their own database because they
are destructive.
"""

import pytest
from alembic import command
from alembic.util.exc import AutogenerateDiffsDetected

from tests.support import database as db

pytestmark = pytest.mark.integration

EXPECTED_TABLES = {"companies", "jobs", "crawl_runs", "crawl_company_results"}


def test_upgrade_from_empty_database_creates_every_table(
    migration_database_url: str,
) -> None:
    db.drop_all_tables(migration_database_url)

    db.upgrade(migration_database_url)

    assert db.table_names(migration_database_url) >= EXPECTED_TABLES


def test_downgrade_returns_the_database_to_empty(migration_database_url: str) -> None:
    db.drop_all_tables(migration_database_url)
    db.upgrade(migration_database_url)

    db.downgrade(migration_database_url)

    remaining = db.table_names(migration_database_url) - {"alembic_version"}
    assert remaining == set()


def test_upgrade_downgrade_upgrade_is_repeatable(migration_database_url: str) -> None:
    # Proves downgrade truly reverses upgrade; a partial downgrade would make
    # the second upgrade fail on an already-existing object.
    db.drop_all_tables(migration_database_url)

    db.upgrade(migration_database_url)
    db.downgrade(migration_database_url)
    db.upgrade(migration_database_url)

    assert db.table_names(migration_database_url) >= EXPECTED_TABLES


def test_alembic_check_reports_no_drift(migration_database_url: str) -> None:
    # The migration and the SQLAlchemy models must describe the same schema.
    db.drop_all_tables(migration_database_url)
    db.upgrade(migration_database_url)

    command.check(db.alembic_config(migration_database_url))


def test_alembic_check_detects_drift(migration_database_url: str) -> None:
    # Guards the guard: if check() could never fail, the test above is vacuous.
    db.drop_all_tables(migration_database_url)
    db.upgrade(migration_database_url)
    db.drop_table(migration_database_url, "crawl_company_results")

    with pytest.raises(AutogenerateDiffsDetected):
        command.check(db.alembic_config(migration_database_url))

    db.drop_all_tables(migration_database_url)
    db.upgrade(migration_database_url)


# --- revision 0002: source consistency --------------------------------------

INITIAL = "73e5941d42ce"
SOURCE_CONSISTENCY = "0002_source_consistency"
NOT_BLANK = "0003_source_job_id_not_blank"
PREVIOUS_HASH = "0004_previous_content_hash"


def test_upgrade_through_0002_creates_the_composite_foreign_key(
    migration_database_url: str,
) -> None:
    db.drop_all_tables(migration_database_url)

    db.upgrade(migration_database_url, SOURCE_CONSISTENCY)

    company_keys = [
        fk
        for fk in db.foreign_keys(migration_database_url, "jobs")
        if fk["referred_table"] == "companies"
    ]
    assert len(company_keys) == 1
    assert company_keys[0]["constrained_columns"] == ["company_id", "source"]
    assert company_keys[0]["referred_columns"] == ["id", "source"]
    assert "uq_companies_id_source" in db.unique_constraint_names(
        migration_database_url, "companies"
    )


def test_downgrade_of_0002_restores_the_simple_foreign_key(
    migration_database_url: str,
) -> None:
    db.drop_all_tables(migration_database_url)
    db.upgrade(migration_database_url, SOURCE_CONSISTENCY)

    db.downgrade(migration_database_url, INITIAL)

    company_keys = [
        fk
        for fk in db.foreign_keys(migration_database_url, "jobs")
        if fk["referred_table"] == "companies"
    ]
    assert len(company_keys) == 1
    assert company_keys[0]["constrained_columns"] == ["company_id"]
    assert "uq_companies_id_source" not in db.unique_constraint_names(
        migration_database_url, "companies"
    )


def test_job_identity_constraint_survives_both_directions(
    migration_database_url: str,
) -> None:
    # UNIQUE (source, source_job_id) must be untouched by 0002.
    db.drop_all_tables(migration_database_url)

    db.upgrade(migration_database_url, SOURCE_CONSISTENCY)
    assert "uq_jobs_source_job_id" in db.unique_constraint_names(
        migration_database_url, "jobs"
    )

    db.downgrade(migration_database_url, INITIAL)
    assert "uq_jobs_source_job_id" in db.unique_constraint_names(
        migration_database_url, "jobs"
    )


def test_upgrade_through_0003_creates_the_not_blank_check(
    migration_database_url: str,
) -> None:
    db.drop_all_tables(migration_database_url)

    db.upgrade(migration_database_url, NOT_BLANK)

    assert "ck_jobs_source_job_id_not_blank" in db.check_constraint_names(
        migration_database_url, "jobs"
    )


def test_downgrade_of_0003_removes_the_not_blank_check(
    migration_database_url: str,
) -> None:
    db.drop_all_tables(migration_database_url)
    db.upgrade(migration_database_url, NOT_BLANK)

    db.downgrade(migration_database_url, SOURCE_CONSISTENCY)

    assert "ck_jobs_source_job_id_not_blank" not in db.check_constraint_names(
        migration_database_url, "jobs"
    )


def test_upgrade_through_0004_adds_previous_content_hash(
    migration_database_url: str,
) -> None:
    db.drop_all_tables(migration_database_url)

    db.upgrade(migration_database_url, PREVIOUS_HASH)

    assert "previous_content_hash" in db.column_names(migration_database_url, "jobs")


def test_downgrade_of_0004_removes_previous_content_hash(
    migration_database_url: str,
) -> None:
    db.drop_all_tables(migration_database_url)
    db.upgrade(migration_database_url, PREVIOUS_HASH)

    db.downgrade(migration_database_url, NOT_BLANK)

    assert "previous_content_hash" not in db.column_names(
        migration_database_url, "jobs"
    )
